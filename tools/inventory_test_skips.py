#!/usr/bin/env python3
"""Inventory pytest skip markers and write docs/TEST_SKIPS.md."""

from __future__ import annotations

import argparse
import re
import sys
from collections import defaultdict
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[1]
SCAN_ROOTS = (REPO_ROOT / "tests", REPO_ROOT / "python" / "uacalc" / "tests")

if str(REPO_ROOT / "tools") not in sys.path:
    sys.path.insert(0, str(REPO_ROOT / "tools"))
from strict_skip_policy import is_allowed_skip_reason, is_guard_skip_reason  # noqa: E402

SKIP_PATTERNS = (
    re.compile(r"@pytest\.mark\.skip(?:if)?\s*\("),
    re.compile(r"pytest\.skip\s*\("),
    re.compile(r"pytest\.mark\.skipif"),
)


def classify(reason: str) -> str:
    reason = (reason or "").strip()
    if is_allowed_skip_reason(reason):
        if reason.lower().startswith("slow:") or "heavy" in reason.lower():
            return "slow"
        if reason.lower().startswith("platform:"):
            return "platform"
        return "environment"
    if is_guard_skip_reason(reason):
        return "guard"
    r = reason.lower()
    if "slow" in r or "heavy" in r or "memory" in r:
        return "slow"
    if "win32" in r or "windows" in r or "stack overflow" in r:
        return "platform"
    if any(x in r for x in ("jython", "java", "jar", "wrapper not available")):
        return "environment"
    if "stub" in r or "not implemented" in r:
        return "hiding-a-gap"
    return "other"


def extract_reason(line: str, lines: list[str], idx: int) -> str:
    chunk = line
    if "(" in line and line.count("(") > line.count(")"):
        for j in range(idx + 1, min(idx + 8, len(lines))):
            chunk += " " + lines[j].strip()
            if chunk.count("(") <= chunk.count(")"):
                break
    for pat in (
        r'reason\s*=\s*"([^"]*)"',
        r"reason\s*=\s*'([^']*)'",
        r'pytest\.skip\s*\(\s*"([^"]*)"',
        r"pytest\.skip\s*\(\s*f\"([^\"]*)\"",
    ):
        m = re.search(pat, chunk)
        if m:
            return m.group(1).strip()
    return chunk.strip()[:160]


def scan_file(path: Path) -> list[tuple[int, str, str]]:
    text = path.read_text(encoding="utf-8", errors="replace")
    lines = text.splitlines()
    hits: list[tuple[int, str, str]] = []
    for i, line in enumerate(lines):
        if not any(p.search(line) for p in SKIP_PATTERNS):
            continue
        reason = extract_reason(line, lines, i)
        hits.append((i + 1, classify(reason), reason))
    return hits


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument(
        "--check",
        action="store_true",
        help="Fail if hiding-a-gap, or other guard-like skips remain",
    )
    args = parser.parse_args()

    by_class: dict[str, list[str]] = defaultdict(list)
    total = 0
    for root in SCAN_ROOTS:
        if not root.is_dir():
            continue
        for path in sorted(root.rglob("*.py")):
            if ".venv" in path.parts or "jython_scripts" in path.parts:
                continue
            try:
                entries = scan_file(path)
            except OSError:
                continue
            for line_no, cat, reason in entries:
                total += 1
                rel = path.relative_to(REPO_ROOT)
                by_class[cat].append(f"- `{rel}`:{line_no} — {reason}")

    if args.check:
        bad = []
        for item in by_class.get("hiding-a-gap", []):
            bad.append(item)
        for item in by_class.get("other", []):
            reason = item.split(" — ", 1)[-1]
            if is_guard_skip_reason(reason) and not is_allowed_skip_reason(reason):
                bad.append(item)
        if bad:
            print("Unclassified guard-like skips (fix or prefix with Environment:/optional:):")
            for line in bad:
                print(" ", line)
            return 1

    out = REPO_ROOT / "docs" / "TEST_SKIPS.md"
    sections = [
        "# Test skips inventory",
        "",
        "Strict CI sets `UACALC_STRICT_TESTS=1`: guard skips fail; skips whose reason "
        "starts with `Environment:`, `slow:`, `platform:`, or `optional:` are allowed.",
        "",
        f"Generated by `tools/inventory_test_skips.py` ({total} skip sites in "
        "`tests/` and `python/uacalc/tests/`).",
        "",
        "## Summary",
        "",
    ]
    for cat in (
        "guard",
        "environment",
        "slow",
        "platform",
        "hiding-a-gap",
        "other",
    ):
        sections.append(f"- **{cat}**: {len(by_class.get(cat, []))}")
    sections.append("")
    for cat in (
        "guard",
        "environment",
        "slow",
        "platform",
        "hiding-a-gap",
        "other",
    ):
        items = by_class.get(cat, [])
        if not items:
            continue
        sections.extend([f"## {cat}", ""] + items + [""])
    out.write_text("\n".join(sections), encoding="utf-8")
    print(f"Wrote {out} ({total} entries)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())